#!/bin/sh
# GT827 touch controller test from userspace (no kernel driver).
# Protocol recovered from the vendor module gt82x_up.ko (Android, kernel 3.0):
#   reset   : PB3 (gpiochip0 line 35) low -> high
#   config  : 112 bytes written to 0x0F80 (RAM only, a reset clears it)
#   version : 3 bytes at 0x0F7D
#   touch   : 8 bytes at 0x0F40; byte0 bit7 = valid, bits0-4 = finger mask;
#             byte1 low nibble 0xF = "send me the config"
#   after every access: "end command" = write 0x80 0x00
# Run on the tablet:  sudo sh gt827-test.sh
set -e
A=0x5d
CFG="0x00 0x0f 0x01 0x10 0x02 0x11 0x03 0x12 0x04 0x13 0x05 0x14 0x06 0x15 0x07 0x16 0x08 0x17 0x09 0x18 0x0a 0x19 0x0b 0x1a 0x0c 0x1b 0x0d 0x1c 0xff 0xff 0x02 0x0c 0x03 0x0d 0x04 0x0e 0x05 0x0f 0x06 0x10 0x07 0x11 0x08 0x12 0x09 0x13 0xff 0xff 0xff 0xff 0x1f 0x03 0x88 0x00 0x00 0x2d 0x00 0x00 0x07 0x00 0x00 0x0a 0x6a 0x55 0x1d 0x03 0x00 0x05 0x00 0x01 0xe0 0x03 0x20 0x41 0x40 0x43 0x43 0x28 0x00 0x05 0x19 0x02 0x14 0x10 0x00 0x02 0x00 0x00 0x00 0x00 0x00 0x00 0x50 0x00 0x60 0x20 0x00 0x00 0x00 0x00 0x09 0x88 0x2c 0x00 0x00 0x01 0x00 0x00 0x00 0x00 0x00 0x01"
fim() { i2ctransfer -y 1 w2@$A 0x80 0x00; }

pkill gpioset 2>/dev/null || true
sleep 0.1
echo "== reset (PB3 low 50 ms, then high)"
gpioset -c gpiochip0 -t 50ms,0 35=0 &
sleep 0.3

echo "== antes da configuracao / before config:"
echo "   0x0F40: $(i2ctransfer -y 1 w2@$A 0x0f 0x40 r8)"; fim

echo "== a enviar a configuracao / sending config (112 bytes -> 0x0F80)"
i2ctransfer -y 1 w114@$A 0x0f 0x80 $CFG
fim
sleep 0.2

echo "== versao / version 0x0F7D: $(i2ctransfer -y 1 w2@$A 0x0f 0x7d r3)"; fim
echo "== config lida / config read back (first 16): $(i2ctransfer -y 1 w2@$A 0x0f 0x80 r16)"; fim

echo "== toca no ecra durante 15 s / touch the screen for 15 s"
i=0
while [ $i -lt 75 ]; do
    echo "$i: $(i2ctransfer -y 1 w2@$A 0x0f 0x40 r8)"
    fim
    sleep 0.2
    i=$((i+1))
done
pkill gpioset
echo "== fim / done"
